// Generates src/generated/{prisma,openapi}.ts and openapi.json from apps/api.
// Requires apps/api to be built (turbo runs @4kidstudy/api#build first).
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const apiDir = join(pkgDir, '../../apps/api');
const outDir = join(pkgDir, 'src/generated');
mkdirSync(outDir, { recursive: true });

const HEADER =
  '// Code generated by packages/contracts/scripts/generate.mjs. DO NOT EDIT.\n';

// ---------------------------------------------------------------- Prisma
// The generated client (from `prisma generate` in apps/api) carries the DMMF.
const { Prisma } = createRequire(join(apiDir, 'package.json'))(
  '@prisma/client',
);
const { enums, models } = Prisma.dmmf.datamodel;

// Prisma scalar -> type as it arrives over JSON.
const SCALARS = {
  String: 'string',
  Int: 'number',
  Float: 'number',
  Boolean: 'boolean',
  DateTime: 'string', // ISO-8601 after JSON serialization
  BigInt: 'string',
  Decimal: 'string',
  Json: 'unknown',
  Bytes: 'unknown',
};

const out = [HEADER];
out.push('// ---- Enums (apps/api/prisma/schema.prisma) ----\n');
for (const e of enums) {
  out.push(`export const ${e.name} = {`);
  for (const v of e.values) out.push(`  ${v.name}: '${v.name}',`);
  out.push('} as const;');
  out.push(
    `export type ${e.name} = (typeof ${e.name})[keyof typeof ${e.name}];\n`,
  );
}
out.push(
  '// ---- Models: scalar fields as serialized to JSON (relations excluded) ----\n',
);
for (const m of models) {
  const relations = [];
  out.push(`export interface ${m.name} {`);
  for (const f of m.fields) {
    if (f.kind === 'object') {
      relations.push(f.name);
      continue;
    }
    let t = f.kind === 'enum' ? f.type : SCALARS[f.type];
    if (!t)
      throw new Error(`Unmapped Prisma type ${f.type} on ${m.name}.${f.name}`);
    if (f.isList) t = `${t}[]`;
    if (!f.isRequired) t = `${t} | null`;
    out.push(`  ${f.name}: ${t};`);
  }
  out.push('}');
  out.push(
    `export type ${m.name}Relation = ${relations.length ? relations.map((r) => `'${r}'`).join(' | ') : 'never'};\n`,
  );
}
writeFileSync(join(outDir, 'prisma.ts'), out.join('\n'));

// ---------------------------------------------------------------- OpenAPI
// apps/api/dist/openapi.js builds the Swagger document without connecting to the DB.
const json = execFileSync(process.execPath, [join(apiDir, 'dist/openapi.js')], {
  cwd: apiDir,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
const spec = JSON.parse(json);
writeFileSync(
  join(pkgDir, 'openapi.json'),
  JSON.stringify(spec, null, 2) + '\n',
);
const ast = await openapiTS(spec, { alphabetize: true });
writeFileSync(join(outDir, 'openapi.ts'), HEADER + astToString(ast));

console.log(
  `contracts: ${enums.length} enums, ${models.length} models, ` +
    `${Object.keys(spec.paths ?? {}).length} paths, ` +
    `${Object.keys(spec.components?.schemas ?? {}).length} schemas`,
);
